// Builds src/engine/dex.generated.ts from the PokeAPI tables in data/ (Gen 1-5: species 1 to 649).
//   node scripts/gen-dex.mjs
import { readFileSync, writeFileSync } from "node:fs";

const MAX = 649;
/** A small CSV reader: the PokeAPI tables have no quoted commas except in names, which are quoted. */
function csv(name) {
  const [head, ...lines] = readFileSync(new URL(`../data/${name}.csv`, import.meta.url), "utf8").trim().split("\n");
  const keys = head.split(",");
  return lines.map((line) => {
    const cells = [];
    let cell = "";
    let quoted = false;
    for (const ch of line) {
      if (ch === '"') quoted = !quoted;
      else if (ch === "," && !quoted) (cells.push(cell), (cell = ""));
      else cell += ch;
    }
    cells.push(cell);
    return Object.fromEntries(keys.map((k, i) => [k, cells[i] ?? ""]));
  });
}

const TYPE_NAMES = ["normal", "fighting", "flying", "poison", "ground", "rock", "bug", "ghost", "steel", "fire", "water", "grass", "electric", "psychic", "ice", "dragon", "dark", "fairy"];
const species = csv("pokemon_species").filter((s) => +s.id <= MAX);
const names = new Map(csv("pokemon_species_names").filter((n) => n.local_language_id === "9").map((n) => [+n.pokemon_species_id, n.name]));
const types = new Map();
for (const t of csv("pokemon_types")) if (+t.pokemon_id <= MAX) (types.get(+t.pokemon_id) ?? types.set(+t.pokemon_id, []).get(+t.pokemon_id))[+t.slot - 1] = +t.type_id - 1;
const bst = new Map();
for (const s of csv("pokemon_stats")) if (+s.pokemon_id <= MAX) bst.set(+s.pokemon_id, (bst.get(+s.pokemon_id) ?? 0) + +s.base_stat);
const evo = new Map();
for (const e of csv("pokemon_evolution")) {
  const id = +e.evolved_species_id;
  if (id > MAX) continue;
  const level = e.minimum_level ? +e.minimum_level : 0;
  const prev = evo.get(id);
  if (!prev || (level && (!prev.level || level < prev.level))) evo.set(id, { level, trigger: +e.evolution_trigger_id });
}

const fromOf = new Map(species.map((s) => [+s.id, s.evolves_from_species_id ? +s.evolves_from_species_id : 0]));
const stageOf = (id) => (fromOf.get(id) ? 1 + stageOf(fromOf.get(id)) : 1);
const ascii = (n) => n.replace("♀", " F").replace("♂", " M").replace("é", "e").replace("’", "'");

const rows = species.map((s) => {
  const id = +s.id;
  const t = types.get(id) ?? [0];
  const stage = stageOf(id);
  const info = evo.get(id);
  // evolutions by item, trade or friendship have no level in the data: give them one by stage
  const evoLevel = fromOf.get(id) ? info?.level || (stage === 2 ? 30 : 44) : 0;
  const flags = (+s.is_legendary ? 1 : 0) | (+s.is_mythical ? 2 : 0) | (+s.is_baby ? 4 : 0);
  return [id, ascii(names.get(id) ?? s.identifier), t[0] ?? 0, t[1] ?? -1, bst.get(id) ?? 300, +s.capture_rate, +s.generation_id, fromOf.get(id) ?? 0, evoLevel, flags, stage];
});

const out = `/* Generated by scripts/gen-dex.mjs from the PokeAPI tables in data/. Do not edit by hand. */

/** id, name, type 1, type 2 (-1 for none), base stat total, capture rate, generation, evolves from, evolution level, flags (1 legendary, 2 mythical, 4 baby), stage */
export type DexRow = readonly [number, string, number, number, number, number, number, number, number, number, number];

export const TYPE_NAMES = ${JSON.stringify(TYPE_NAMES)} as const;

export const DEX_ROWS: readonly DexRow[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;
writeFileSync(new URL("../src/engine/dex.generated.ts", import.meta.url), out);
console.log(`${rows.length} species, ${out.length} bytes`);
